'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {createEmptyLedger,applyDecision}=require('../event-capacity-decision-ledger');
const {signPrivateSnapshot,verifyPrivateSnapshot}=require('../event-capacity-snapshot-attestation');
const SCOPE={guildId:'1114967437788577792',forumId:'1550619824005062697'};
const SECRET='high-entropy-synthetic-unit-test-source-signing-secret-v1';
const WRONG='high-entropy-synthetic-unit-test-source-signing-secret-v2';
const NOW=Date.parse('2027-03-20T12:00:00Z');
const options={scope:SCOPE,secret:SECRET,nowMs:NOW};
function original(){
  const report={
    guildId:SCOPE.guildId,forumId:SCOPE.forumId,generatedAt:'2027-03-20T11:54:00Z',
    finalization:{finalizedAt:'2027-03-20T11:56:00Z'},
    summary:{totalThreads:1,actualConvoys:1},
    threads:[{threadId:'150000000000000001',eventId:'12345',status:'Scheduled',
      validation:{parsed:{departureAtUtc:'2027-03-20T16:00:00Z'}},
      staffStatus:{authorId:'private-actor',matchedRoleIds:['private-role'],status:'Scheduled',
        roleSource:'message.member'}}]
  };
  const overview={
    guildId:SCOPE.guildId,forumId:SCOPE.forumId,generatedAt:'2027-03-20T11:57:00Z',
    overall:{realConvoySubmissions:1,convoyReadErrors:0,
      legacyImportedConvoys:0,legacyDuplicatesSuppressed:0},
    registeredConvoys:[{source:'convoy-center',threadId:'150000000000000001',
      eventId:'12345',status:'Scheduled',departureAtUtc:'2027-03-20T16:00:00Z'}]
  };
  const ledger=createEmptyLedger(SCOPE,'2027-03-20T11:00:00Z');
  return {report,overview,ledger,integrityVerified:true};
}
function attested(source=original()){
  return {...source,attestation:signPrivateSnapshot(source,{
    ...options,runId:'45502949674',attempt:1,trustedProducer:true
  })};
}
test('Attested private snapshot verifies same report, overview, ledger and scope',()=>{
  const signed=attested();
  const result=verifyPrivateSnapshot(signed,options);
  assert.deepEqual(result,{verified:true,runId:'45502949674',attempt:1});
  assert.equal(JSON.stringify(signed.attestation).includes('private-actor'),false);
  assert.equal(JSON.stringify(signed.attestation).includes('12345'),false);
});
test('Raw source content changed after attestation is rejected',()=>{
  const src=attested();
  src.report.threads[0].status='Cancelled';
  assert.throws(()=>verifyPrivateSnapshot(src,options));
});
test('A changed Overview registration is rejected even with equal record counts',()=>{
  const src=attested();
  src.overview.registeredConvoys[0].departureAtUtc='2027-03-21T16:00:00Z';
  assert.throws(()=>verifyPrivateSnapshot(src,options));
});
test('A changed or higher-revision private decision ledger invalidates the signature',()=>{
  const src=attested();
  src.ledger=applyDecision(src.ledger,{
    ref:'event:12345',action:'classification',value:'Partner Convoy',
    evidenceRef:'private-proof',expectedRevision:0
  },{id:'actor-in-private-store',verifiedRoles:['Event Coordination'],
     source:'trusted-server-gateway'},'2027-03-20T11:55:00Z');
  assert.throws(()=>verifyPrivateSnapshot(src,options));
});
test('A wrong secret or cross-guild scope fails closed without source fields in error',()=>{
  const signed=attested();
  assert.throws(()=>verifyPrivateSnapshot(signed,{...options,secret:WRONG}));
  assert.throws(()=>verifyPrivateSnapshot(signed,{
    ...options,scope:{guildId:'222222222222222222',forumId:SCOPE.forumId}
  }));
});
test('Forgeries without a valid MAC or unknown extra proof fields are rejected',()=>{
  const src=attested();
  assert.throws(()=>verifyPrivateSnapshot({...src,attestation:{...src.attestation,mac:'0'.repeat(64)}},options));
  assert.throws(()=>verifyPrivateSnapshot({...src,attestation:{...src.attestation,unexpected:'unsafe'}},options));
  assert.throws(()=>verifyPrivateSnapshot({...src,attestation:{...src.attestation,version:2}},options));
});
test('Source/issuer HMAC must be generated by an explicitly trusted private producer',()=>{
  const source=original();
  assert.throws(()=>signPrivateSnapshot(source,{...options,runId:'45502949674',attempt:1}));
  assert.throws(()=>signPrivateSnapshot(source,{...options,runId:'invalid',attempt:1,trustedProducer:true}));
  assert.throws(()=>signPrivateSnapshot(source,{...options,runId:'45502949674',attempt:0,trustedProducer:true}));
  assert.throws(()=>signPrivateSnapshot(source,{...options,runId:'45502949674',attempt:1,trustedProducer:true,secret:'weak'}));
});
test('Source timestamp chronology and incomplete old snapshots cannot be attested',()=>{
  const source=original();
  source.report.finalization.finalizedAt='2027-03-20T11:50:00Z';
  assert.throws(()=>signPrivateSnapshot(source,{...options,runId:'45502949674',attempt:1,trustedProducer:true}));
  const old=original();
  old.overview.generatedAt='2027-03-20T10:00:00Z';
  assert.throws(()=>signPrivateSnapshot(old,{...options,runId:'45502949674',attempt:1,trustedProducer:true}));
});
test('An old but authentic signed artifact cannot be replayed after freshness window',()=>{
  const src=attested();
  assert.throws(()=>verifyPrivateSnapshot(src,{...options,nowMs:NOW+31*60000}));
});
test('A truncated Center inventory or legacy collision cannot be attested',()=>{
  const src=original();
  src.overview.registeredConvoys=[];
  assert.throws(()=>signPrivateSnapshot(src,{...options,runId:'45502949674',attempt:1,trustedProducer:true}));
  const legacy=original();
  legacy.overview.overall.legacyImportedConvoys=1;
  legacy.overview.registeredConvoys.push({source:'legacy-calendar',eventId:'12345',threadId:'legacy'});
  assert.throws(()=>signPrivateSnapshot(legacy,{...options,runId:'45502949674',attempt:1,trustedProducer:true}));
});
test('Object property insertion order does not cause false rejection',()=>{
  const src=attested();
  src.report.threads[0]={...{status:src.report.threads[0].status},
    ...src.report.threads[0]};
  assert.equal(verifyPrivateSnapshot(src,options).verified,true);
});
test('Missing attestation cannot be accepted as verified source',()=>{
  assert.throws(()=>verifyPrivateSnapshot(original(),options));
});
test('Plaintext source identifiers do not appear in cryptographic errors',()=>{
  const src=attested();
  src.report.threads[0].name='Never print this private title';
  assert.throws(()=>verifyPrivateSnapshot(src,options),
    error=>!String(error.message).includes('Never print'));
});
